#define REQUIRE(condition, label) do { \
    if (!(condition)) { \
        fprintf(stderr, "FAIL security chain copy: %s\n", label); \
        goto cleanup; \
    } \
} while (0)

int main(void)
{
    typedef CFArrayRef (*copy_chain_fn)(SecTrustRef);
    copy_chain_fn copy_chain = (copy_chain_fn)dlsym(RTLD_DEFAULT, "SecTrustCopyCertificateChain");
    CFDataRef expected = NULL, actual = NULL;
    SecCertificateRef certificate = NULL;
    SecPolicyRef policy = NULL;
    SecTrustRef trust = NULL;
    CFDateRef date = NULL;
    CFArrayRef first = NULL, second = NULL;
    SecTrustResultType verdict = kSecTrustResultInvalid;
    int result = 1;

    REQUIRE(copy_chain != NULL, "public chain-copy API is available");
    REQUIRE(copy_chain(NULL) == NULL, "null trust has no chain");
    expected = CFDataCreate(NULL, _c0, sizeof(_c0));
    REQUIRE(expected != NULL, "create fixed certificate DER");
    certificate = SecCertificateCreateWithData(NULL, expected);
    policy = SecPolicyCreateBasicX509();
    REQUIRE(certificate != NULL && policy != NULL, "create certificate and real X509 policy");
    REQUIRE(SecTrustCreateWithCertificates(certificate, policy, &trust) == errSecSuccess,
            "create trust object");
    /* January 1, 2020: this certificate expired in March 2019. */
    date = CFDateCreate(NULL, 599529600.0);
    REQUIRE(date != NULL && SecTrustSetVerifyDate(trust, date) == errSecSuccess,
            "set deterministic expired evaluation date");
    REQUIRE(SecTrustSetNetworkFetchAllowed(trust, false) == errSecSuccess,
            "keep evaluation offline");
    first = copy_chain(trust);
    second = copy_chain(trust);
    REQUIRE(first != NULL && second != NULL, "lazy evaluation returns chain snapshots");
    REQUIRE(SecTrustGetTrustResult(trust, &verdict) == errSecSuccess &&
            (verdict == kSecTrustResultRecoverableTrustFailure || verdict == kSecTrustResultFatalTrustFailure),
            "copying a chain does not turn an expired certificate into trusted success");
    CFRelease(trust);
    trust = NULL;
    CFRelease(certificate);
    certificate = NULL;
    REQUIRE(CFArrayGetCount(first) >= 1 && CFArrayGetCount(second) >= 1,
            "snapshots retain the leaf after trust destruction");
    actual = SecCertificateCopyData((SecCertificateRef)CFArrayGetValueAtIndex(first, 0));
    REQUIRE(actual != NULL && CFEqual(actual, expected), "first snapshot preserves exact leaf DER");
    CFRelease(actual);
    actual = NULL;
    CFRelease(first);
    first = NULL;
    actual = SecCertificateCopyData((SecCertificateRef)CFArrayGetValueAtIndex(second, 0));
    REQUIRE(actual != NULL && CFEqual(actual, expected),
            "second owned snapshot survives release of the first");
    result = 0;

cleanup:
    if (actual) CFRelease(actual);
    if (first) CFRelease(first);
    if (second) CFRelease(second);
    if (date) CFRelease(date);
    if (trust) CFRelease(trust);
    if (policy) CFRelease(policy);
    if (certificate) CFRelease(certificate);
    if (expected) CFRelease(expected);
    if (result == 0) puts("SECURITY_CHAIN_COPY_GUEST_OK");
    return result;
}
