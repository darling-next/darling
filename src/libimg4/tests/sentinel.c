static void replacing_owned_attachment(void)
{
    uint64_t storage[IMG4_FIRMWARE_STRUCT_RECOMMENDED_SIZE / sizeof(uint64_t)];
    img4_buff_t first;
    img4_firmware_t firmware = attach_input(storage, genuine_manifest,
        sizeof(genuine_manifest), IMG4_FIRMWARE_FLAG_SUBSEQUENT_STAGE, &first);
    release.firmware = &firmware;
    img4_buff_t second = IMG4_BUFF_INIT;
    second.i4b_bytes = copy_input(genuine_manifest, sizeof(genuine_manifest));
    second.i4b_len = sizeof(genuine_manifest);
    second.i4b_dealloc = release_manifest;
    img4_firmware_attach_manifest(firmware, &second);
    CHECK(release.count == 1);
    CHECK(second.i4b_dealloc == NULL);
    release.bytes = second.i4b_bytes;
    release.length = second.i4b_len;
    release.count = 0;
    CHECK(select_generic(firmware) == IMG4_CHIP_CRYPTEX1_GENERIC_X86);
    destroy_input(&firmware);
}

static void missing_runtime_identity_preserves_output(void)
{
    const img4_runtime_t *runtime = IMG4_RUNTIME_DEFAULT;
    bool boolean = true;
    uint32_t integer32 = 0x12345678;
    uint64_t integer64 = UINT64_C(0x123456789abcdef0);
    img4_dgst_t digest = IMG4_DGST_INIT;
    digest.i4d_len = 17;
    digest.i4d_bytes[0] = 0x5a;
    CHECK(runtime->i4rt_get_identifier_bool(runtime, IMG4_CHIP_CRYPTEX1_GENERIC_X86,
        UINT64_MAX, &boolean) == ENOTSUP);
    CHECK(boolean == true);
    CHECK(runtime->i4rt_get_identifier_uint32(runtime, IMG4_CHIP_CRYPTEX1_GENERIC_X86,
        UINT64_MAX, &integer32) == ENOTSUP);
    CHECK(integer32 == 0x12345678);
    CHECK(runtime->i4rt_get_identifier_uint64(runtime, IMG4_CHIP_CRYPTEX1_GENERIC_X86,
        UINT64_MAX, &integer64) == ENOTSUP);
    CHECK(integer64 == UINT64_C(0x123456789abcdef0));
    CHECK(runtime->i4rt_get_identifier_digest(runtime, IMG4_CHIP_CRYPTEX1_GENERIC_X86,
        IMG4_IDENTIFIER_CHMH, &digest) == ENOTSUP);
    CHECK(digest.i4d_len == 17 && digest.i4d_bytes[0] == 0x5a);

    /* Exercise the live identity oracle without assuming a particular machine
     * has production fuses. Errors must not replace absent state with false.
     */
    int error = runtime->i4rt_get_identifier_bool(runtime,
        IMG4_CHIP_CRYPTEX1_GENERIC_X86, IMG4_IDENTIFIER_CPRO, &boolean);
    CHECK(error == 0 || error == ENOENT || error == ENODEV || error == ENOTSUP);
    if (error)
        CHECK(boolean == true);
    printf("CPRO_QUERY_RC=%d\n", error);
}

